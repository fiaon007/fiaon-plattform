/** Punkt-in-Polygon (Strahlverfahren). */
export function liegtIn(lon: number, lat: number, poly: readonly Punkt[]): boolean {
  let drin = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) drin = !drin;
  }
  return drin;
}

export const istLand = (lon: number, lat: number) => LAND.some((p) => liegtIn(lon, lat, p));
